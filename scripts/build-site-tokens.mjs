/**
 * The site's design tokens → CSS and the reference page (docs: documentation/site-ui/design-system.md §2).
 *
 * src/site/design/site.resolver.json (W3C DTCG 2025.10 resolver: the base set tokens.json, then the
 * theme modifier's light and dark contexts) is the source of truth. This writes:
 *   - src/site/styles/tokens.css: every token as a custom property; aliases stay var() references,
 *     colour roles that differ between the contexts become light-dark() pairs and fluid sizes clamp();
 *   - src/site/styles/editor-tokens.css: the `c.editor` and `c.editor-*` tokens (edit mode, the local CMS), which only
 *     the editor imports, so none of them reach a production page;
 *   - documentation/site-ui/tokens.md: the token reference for the docs site (a `$deprecated` token marked);
 *   - src/site/design/token-history.json and documentation/site-ui/token-changelog.md: the changelog,
 *     from the last built token set (scripts/lib/token-changelog.mjs);
 *   - src/site/design/responsive.ts: the breakpoints, measures and picture widths for scripts and props
 *     (matchMedia, a picture's sizes), with the media() and sizes() helpers.
 * Never hand-edit any of them. `node scripts/build-site-tokens.mjs --check` fails if they're out of date.
 * The game's tokens are separate: scripts/build-tokens.mjs.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadSite, cssValue, cssMore, resolve, resolveMore, groupOf, tier, toCss, FLUID_FROM, FLUID_TO } from '../src/site/design/tokenModel.ts';
import { snapshotOf, update, parseHistory, historyJson, renderChangelog, today, codeNames } from './lib/token-changelog.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DESIGN = join(ROOT, 'src/site/design');
export const RESOLVER = join(DESIGN, 'site.resolver.json');
export const CSS_OUT = join(ROOT, 'src/site/styles/tokens.css');
export const EDITOR_CSS_OUT = join(ROOT, 'src/site/styles/editor-tokens.css');
/** Edit mode's own tokens (the shared `c.editor` group and each part's `c.editor-*`): written apart, imported only by the editor. */
export const isEditorToken = (t) => t.path[0] === 'c' && (t.path[1] === 'editor' || t.path[1].startsWith('editor-'));
export const DOC_OUT = join(ROOT, 'documentation/site-ui/tokens.md');
export const RESPONSIVE_OUT = join(DESIGN, 'responsive.ts');

const readJson = (f) => JSON.parse(readFileSync(f, 'utf8'));
const model = () => loadSite(readJson(RESOLVER), (ref) => readJson(join(DESIGN, ref)));

const HEADER = `/* GENERATED by scripts/build-site-tokens.mjs from src/site/design/tokens.json. Do not edit.
 * The site's tokens (not the game's). Tiers: --p-* primitives (private: tokens only) → semantic
 * (--color-*, --text-*, --space-*, …) → component (--c-*). Colour roles are light-dark() pairs: the
 * page follows the system unless <html data-theme> picks one, and any subtree can switch with
 * color-scheme. Docs: documentation/site-ui/design-system.md. */
`;

export function buildCss(m = model()) {
  const lines = [HEADER, ':root {', '  color-scheme: light dark;'];
  for (const t of m.tokens) if (!isEditorToken(t)) lines.push(`  ${t.name}: ${cssValue(t, m.byPath)};`);
  lines.push('}', '');
  lines.push(":root[data-theme='light'] {", '  color-scheme: light;', '}', '');
  lines.push(":root[data-theme='dark'] {", '  color-scheme: dark;', '}', '');
  const more = m.tokens.filter((t) => t.more !== undefined);
  if (more.length) {
    lines.push('/* the contrast modifier\'s "more" context: iOS Increase Contrast and the like */', '@media (prefers-contrast: more) {', '  :root {');
    for (const t of more) lines.push(`    ${t.name}: ${cssMore(t, m.byPath)};`);
    lines.push('  }', '}', '');
  }
  return lines.join('\n');
}

const TIER = { primitive: 'Primitive (private)', semantic: 'Semantic', component: 'Component' };
const esc = (s) => String(s).replace(/\|/g, '\\|');
const code = (s) => `\`${esc(s)}\``;

/** A resolved rem dimension as a number of rem (the module's records hold numbers). */
function remOf(t, byPath) {
  const v = resolve(t, byPath);
  const m = /^(-?[\d.]+)rem$/.exec(v);
  if (!m) throw new Error(`${t.name}: responsive.ts takes rem dimensions only, got ${v}`);
  return Number(m[1]);
}

/**
 * src/site/design/responsive.ts: the breakpoints, measures and picture widths (tokens flagged
 * `site.sizes`) for scripts and props, which can't read a custom property: a matchMedia query and a
 * picture's `sizes`. CSS @media keeps its literals (checked against the breakpoint tokens).
 */
export function buildResponsive(m = model()) {
  const rec = (filter, key) => m.tokens.filter(filter).map((t) => `  ${/^[a-z_]\w*$/i.test(key(t)) ? key(t) : `'${key(t)}'`}: ${remOf(t, m.byPath)},`);
  const lines = [
    '/* GENERATED by scripts/build-site-tokens.mjs from src/site/design/tokens.json. Do not edit.',
    ' * The breakpoints, measures and picture widths, in rem, for scripts and props (matchMedia, a',
    " * picture's sizes), which can't read a custom property. CSS @media keeps its literals.",
    ' * Docs: documentation/site-ui/design-system.md §2. */',
    '',
    '/** The breakpoint tokens (`--breakpoint-*`); `short` is a height. */',
    'export const BREAKPOINTS = {',
    ...rec((t) => t.path[0] === 'breakpoint', (t) => t.path[1]),
    '} as const;',
    '',
    '/** The measures (`--size-*`): the column and the widths figures break out to. */',
    'export const MEASURES = {',
    ...rec((t) => t.path[0] === 'size' && ['measure', 'measure-narrow', 'popout', 'wide', 'max'].includes(t.path[1]), (t) => t.path[1]),
    '} as const;',
    '',
    "/** Picture widths a component shows at (component tokens flagged `site.sizes`), by their name after `--c-`. */",
    'export const PICTURE_WIDTHS = {',
    ...rec((t) => t.extensions?.['site.sizes'] === true, (t) => t.name.replace(/^--c-/, '')),
    '} as const;',
    '',
    'export type Breakpoint = keyof typeof BREAKPOINTS;',
    'export type Measure = keyof typeof MEASURES;',
    'export type PictureWidth = keyof typeof PICTURE_WIDTHS;',
    '/** A width: a measure, a picture width, a share of a measure (a column of several), or a viewport width. */',
    'export type Width = Measure | PictureWidth | { share: Measure; of: number } | `${number}vw`;',
    '',
    "/** A media query at a breakpoint: `media('md')` is `(max-width: 56rem)`; `short` queries the height. */",
    "export function media(bp: Breakpoint, edge: 'max' | 'min' = 'max'): string {",
    "  return `(${edge}-${bp === 'short' ? 'height' : 'width'}: ${BREAKPOINTS[bp]}rem)`;",
    '}',
    '',
    '/** A width as CSS (a share rounds up to a whole rem). */',
    'export function width(w: Width): string {',
    "  if (typeof w === 'object') return `${Math.ceil(MEASURES[w.share] / w.of)}rem`;",
    '  if (w in MEASURES) return `${MEASURES[w as Measure]}rem`;',
    '  if (w in PICTURE_WIDTHS) return `${PICTURE_WIDTHS[w as PictureWidth]}rem`;',
    '  return w;',
    '}',
    '',
    '/**',
    " * A picture's `sizes`: each step is [up to a breakpoint or measure, the width there], then the width",
    " * beyond the last. `sizes(['popout', '92vw'], 'popout')` is `(max-width: 52rem) 92vw, 52rem`.",
    ' */',
    "export function sizes(...steps: [...[Exclude<Breakpoint, 'short'> | Measure, Width][], Width]): string {",
    '  const last = steps[steps.length - 1] as Width;',
    '  const upTo = steps.slice(0, -1) as [Breakpoint | Measure, Width][];',
    "  return [...upTo.map(([at, w]) => `(max-width: ${at in BREAKPOINTS ? BREAKPOINTS[at as Breakpoint] : MEASURES[at as Measure]}rem) ${width(w)}`), width(last)].join(', ');",
    '}',
    '',
  ];
  return lines.join('\n');
}

export function buildEditorCss(m = model()) {
  const lines = [
    '/* GENERATED by scripts/build-site-tokens.mjs from src/site/design/tokens.json (c.editor, c.editor-*). Do not edit.',
    " * Edit mode's own tokens: only the editor imports this file, so none of them reach a production page.",
    ' * Docs: documentation/editor/spec.md §10. */',
    ':root {',
  ];
  for (const t of m.tokens) if (isEditorToken(t)) lines.push(`  ${t.name}: ${cssValue(t, m.byPath)};`);
  lines.push('}', '');
  return lines.join('\n');
}

export function buildDoc(m = model()) {
  const { json, tokens, byPath } = m;
  const groups = new Map();
  for (const t of tokens) {
    const g = groupOf(t);
    if (!groups.has(g)) groups.set(g, []);
    groups.get(g).push(t);
  }
  const out = [
    '# Site design tokens (reference)',
    '',
    '> Generated by `scripts/build-site-tokens.mjs` from `src/site/design/site.resolver.json` (the W3C DTCG 2025.10 base set `tokens.json` and the theme contexts `tokens.light.json` and `tokens.dark.json`). Do not edit this page: change the JSON and run `node scripts/build-site-tokens.mjs`.',
    '',
    `**TL;DR:** ${tokens.length} tokens for the classic site, the landing and the design library, in three tiers: primitives (\`--p-*\`, private), semantic roles and scales, and component tokens (\`--c-*\`). Colour roles have a value in each theme context (emitted as \`light-dark()\`); fluid sizes grow between a ${FLUID_FROM} px and a ${FLUID_TO} px viewport (emitted as \`clamp()\`). The rules for using them are in [the site design system](design-system.md) §2; the live, visual version is the design library at \`/design/tokens/\`.`,
    '',
  ];
  for (const [g, list] of groups) {
    const [a, b] = g.split('.');
    const desc = (b ? json[a]?.[b]?.$description : json[a]?.$description) ?? '';
    const owner = a === 'c' ? json.c?.[b]?.$extensions?.['site.owner'] : undefined;
    out.push(`## \`${g}\` · ${TIER[tier(list[0])]}`, '');
    if (owner) out.push(owner === 'shared' ? '**Shared:** any component may read it.' : `**Owned by** \`${owner}\`: no other component reads it.`, '');
    if (desc) out.push(desc, '');
    const hasDark = list.some((t) => t.dark !== undefined);
    const hasFluid = list.some((t) => t.fluidMin !== undefined);
    if (hasDark) {
      out.push('| Token | Light | Dark | Use |', '|---|---|---|---|');
      for (const t of list) out.push(`| ${code(t.name)} | ${code(resolve(t, byPath, 'light'))} | ${code(resolve(t, byPath, 'dark'))} | ${esc(useOf(t))} |`);
    } else if (hasFluid) {
      out.push(`| Token | At ${FLUID_FROM} px | At ${FLUID_TO} px | Use |`, '|---|---|---|---|');
      for (const t of list) out.push(`| ${code(t.name)} | ${code(t.fluidMin !== undefined ? toCss(t.fluidMin, t.type, () => '') : resolve(t, byPath))} | ${code(resolve(t, byPath))} | ${esc(useOf(t))} |`);
    } else {
      out.push('| Token | Value | Resolves to | Use |', '|---|---|---|---|');
      for (const t of list) {
        const v = cssValue(t, byPath);
        const r = resolve(t, byPath);
        out.push(`| ${code(t.name)} | ${code(v)} | ${v === r ? '' : code(r)} | ${esc(useOf(t))} |`);
      }
    }
    out.push('');
  }
  const more = tokens.filter((t) => t.more !== undefined);
  if (more.length) {
    out.push('## More contrast', '', 'The resolver\'s `contrast` modifier: when the reader asks for more contrast (`prefers-contrast: more`, iOS Increase Contrast), these roles take their strong values, in both themes.', '');
    out.push('| Token | Becomes | Light | Dark |', '|---|---|---|---|');
    for (const t of more) out.push(`| ${code(t.name)} | ${code(cssMore(t, byPath))} | ${code(resolveMore(t, byPath, 'light'))} | ${code(resolveMore(t, byPath, 'dark'))} |`);
    out.push('');
  }
  return out.join('\n');
}

// ---------- the changelog (DS2-09) and the deprecation mark (DS2-10) ----------

export const HISTORY_OUT = join(DESIGN, 'token-history.json');
export const CHANGELOG_OUT = join(ROOT, 'documentation/site-ui/token-changelog.md');

/** A token's "Use" cell: a deprecated one says so first, and what to use instead. */
export function useOf(t) {
  if (t.deprecated === undefined) return t.description;
  const why = typeof t.deprecated === 'string' && t.deprecated ? `: ${codeNames(t.deprecated)}` : '';
  return `**Deprecated**${why}.${t.description ? ` ${t.description}` : ''}`;
}

/** A token's value as the changelog records it: its CSS, and its more-contrast value when it has one. */
const recordedValue = (t, byPath) => (t.more !== undefined ? `${cssValue(t, byPath)}; more contrast: ${cssMore(t, byPath)}` : cssValue(t, byPath));

function readOr(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return null;
  }
}

/**
 * The changelog: the tokens as built now, against the last built set in token-history.json. Returns the
 * history file's and the page's text; the entry is dated `date` (today) only if something changed.
 */
export function buildChangelog(m = model(), date = today(), previous = readOr(HISTORY_OUT)) {
  const snapshot = snapshotOf(m.tokens.map((t) => ({ path: t.path, value: recordedValue(t, m.byPath), deprecated: t.deprecated })));
  const history = update(parseHistory(previous), snapshot, date);
  const page = renderChangelog({
    title: 'Site token changelog',
    tldr: `Every change to the website's design tokens (edit mode's \`c.editor\` included), newest first: what was added, removed, renamed, changed in value or deprecated, by date. ${m.tokens.length} tokens today, ${m.tokens.filter((t) => t.deprecated !== undefined).length} of them deprecated. Generated by \`scripts/build-site-tokens.mjs\`; its \`--check\` fails when the tokens changed without a build.`,
    about: [
      '> Generated by `scripts/build-site-tokens.mjs` from `src/site/design/site.resolver.json`. Do not edit this page: change the JSON and run `node scripts/build-site-tokens.mjs`.',
      "The build compares the tokens with the last set it built (kept in `src/site/design/token-history.json`, generated and committed with them) and records what changed under that day's date. A value is the token's CSS: a colour role's `light-dark()` pair, a fluid size's `clamp()`, and its more-contrast value when it has one. A removed and an added token with the same value in the same group are listed as renamed; a token that now aliases a new one holding its old value, and is newly deprecated, is a rename that keeps the old name for one release ([the site design system](design-system.md) §2, the deprecation rule). Owners and other `$extensions` aren't values and aren't recorded. The tokens themselves are in [tokens.md](tokens.md).",
    ],
    history,
    name: (path) => `--${path.split('.').join('-')}`,
  });
  return { history: historyJson(history), page };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const m = model();
  const css = buildCss(m);
  const editorCss = buildEditorCss(m);
  const doc = buildDoc(m);
  const responsive = buildResponsive(m);
  const changelog = buildChangelog(m);
  if (process.argv.includes('--check')) {
    const stale = [
      [CSS_OUT, css],
      [EDITOR_CSS_OUT, editorCss],
      [DOC_OUT, doc],
      [RESPONSIVE_OUT, responsive],
      [HISTORY_OUT, changelog.history],
      [CHANGELOG_OUT, changelog.page],
    ].filter(([f, want]) => {
      try {
        return readFileSync(f, 'utf8').replace(/\r\n/g, '\n') !== want;
      } catch {
        return true;
      }
    });
    if (stale.length) {
      console.error(`Out of date: ${stale.map(([f]) => f).join(', ')}. Run node scripts/build-site-tokens.mjs`);
      process.exit(1);
    }
    console.log('site tokens up to date');
  } else {
    writeFileSync(CSS_OUT, css);
    writeFileSync(EDITOR_CSS_OUT, editorCss);
    writeFileSync(DOC_OUT, doc);
    writeFileSync(RESPONSIVE_OUT, responsive);
    writeFileSync(HISTORY_OUT, changelog.history);
    writeFileSync(CHANGELOG_OUT, changelog.page);
    console.log(`wrote ${m.tokens.length} site tokens`);
  }
}
