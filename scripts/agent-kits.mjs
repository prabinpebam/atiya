/** The `name` and `description` of a skill or agent file. */
export function frontmatter(/** @type {string} */ text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text);
  if (!m) throw new Error('No frontmatter');
  /** @type {Record<string, string>} */
  const out = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([\w-]+):\s*(.*)$/.exec(line);
    if (!kv) continue;
    let v = kv[2].trim();
    if (v.startsWith("'") && v.endsWith("'")) v = v.slice(1, -1).replace(/''/g, "'");
    else if (v.startsWith('"') && v.endsWith('"')) v = JSON.parse(v);
    out[kv[1]] = v;
  }
  return { name: out.name, description: out.description, body: text.slice(m[0].length) };
}

const yaml = (/** @type {string} */ s) => JSON.stringify(s);

/** A skill's adapter. */
export function skillAdapter(/** @type {string} */ kit, /** @type {string} */ name, /** @type {string} */ description) {
  const note = /** @type {Record<string, string>} */ (SKILL_NOTES)[name];
  if (!note) throw new Error(`${kit} has a skill this repository hasn't placed: ${name} (add it to SKILL_NOTES)`);
  return `---
name: ${name}
description: ${yaml(description)}
---

<!-- ${MARK} from ${kit}/skills/${name}/SKILL.md. Change the script's note, never this file. -->

# ${name}

Read and follow [the canonical \`${name}\` skill](../../../${kit}/skills/${name}/SKILL.md) from the pinned ${kit} kit (if it's missing, run \`git submodule update --init ${kit}\`). Its own links resolve beside it.

This repository's rules come first: AGENTS.md, "Agent kits", and the documents it names. ${note}
`;
}

/** An agent's file: the kit's text, then this repository's inputs. */
export function agentFile(/** @type {string} */ kit, /** @type {string} */ name, /** @type {string} */ description, /** @type {string} */ body) {
  const notes = /** @type {Record<string, string[]>} */ (AGENT_NOTES)[name];
  if (!notes) throw new Error(`${kit} has an agent this repository hasn't placed: ${name} (add it to AGENT_NOTES)`);
  return `---
name: ${name}
description: ${yaml(description)}
---

<!-- ${MARK} from ${kit}/agents/${name}.agent.md. Change the script's notes, never this file. -->

${body.trim()}

## In this repository

AGENTS.md comes first, then this text. ${notes.join(' ')}
`;
}

/** Every file the kits should have here, by path relative to the root. */
export function expected(/** @type {string} */ root = ROOT) {
  /** @type {Map<string, string>} */
  const files = new Map();
  for (const kit of KITS) {
    const dir = join(root, kit);
    if (!existsSync(join(dir, 'skills'))) throw new Error(`${kit} isn't checked out: run git submodule update --init ${kit}`);
    for (const s of readdirSync(join(dir, 'skills')).sort()) {
      const { name, description } = frontmatter(readFileSync(join(dir, 'skills', s, 'SKILL.md'), 'utf8'));
      if (name !== s) throw new Error(`${kit}/skills/${s} is named ${name}`);
      files.set(`.github/skills/${s}/SKILL.md`, skillAdapter(kit, s, description));
    }
    for (const a of readdirSync(join(dir, 'agents')).filter((f) => f.endsWith('.agent.md')).sort()) {
      const { name, description, body } = frontmatter(readFileSync(join(dir, 'agents', a), 'utf8'));
      files.set(`.github/agents/${a}`, agentFile(kit, name, description, body));
    }
  }
  return files;
}

/** Generated files no kit makes any more. */
export function leftovers(/** @type {string} */ root, /** @type {Map<string, string>} */ files) {
  const found = [];
  for (const [folder, pick] of /** @type {[string, (n: string) => string | null][]} */ ([
    ['.github/skills', (n) => `.github/skills/${n}/SKILL.md`],
    ['.github/agents', (n) => (n.endsWith('.agent.md') ? `.github/agents/${n}` : null)],
  ])) {
    if (!existsSync(join(root, folder))) continue;
    for (const n of readdirSync(join(root, folder))) {
      const rel = pick(n);
      if (!rel || files.has(rel) || !existsSync(join(root, rel))) continue;
      if (readFileSync(join(root, rel), 'utf8').includes(MARK)) found.push(rel);
    }
  }
  return found;
}

/** What differs from the kits: missing or stale files, and leftovers. */
export function check(/** @type {string} */ root = ROOT) {
  const files = expected(root);
  const stale = [...files].filter(([rel, text]) => !existsSync(join(root, rel)) || readFileSync(join(root, rel), 'utf8').replace(/\r\n/g, '\n') !== text).map(([rel]) => rel);
  return { stale, leftovers: leftovers(root, files) };
}

function main(/** @type {string[]} */ argv) {
  if (argv.includes('--check')) {
    const { stale, leftovers: extra } = check();
    for (const f of stale) console.error(`stale: ${f}`);
    for (const f of extra) console.error(`left over: ${f}`);
    if (stale.length || extra.length) {
      console.error('Run node scripts/agent-kits.mjs and commit the result.');
      return 1;
    }
    console.log(`Agent kits: ${expected().size} discovery files match ${KITS.join(' and ')}.`);
    return 0;
  }
  const files = expected();
  for (const [rel, text] of files) {
    mkdirSync(dirname(join(ROOT, rel)), { recursive: true });
    writeFileSync(join(ROOT, rel), text);
  }
  for (const rel of leftovers(ROOT, files)) rmSync(rel.startsWith('.github/skills/') ? dirname(join(ROOT, rel)) : join(ROOT, rel), { recursive: true });
  console.log(`Agent kits: wrote ${files.size} discovery files.`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) process.exitCode = main(process.argv.slice(2));
