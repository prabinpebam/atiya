#!/usr/bin/env node
/**
 * Copies the site's generated design tokens and fonts into the app's own pages (src/ui/site/), so the
 * app looks like the site without duplicating its sources: the site's build scripts stay their only
 * writer (AGENTS.md). Run before the app starts (npm start's prestart) and before its tests.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const APP = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = resolve(APP, '..', '..', 'src', 'site');
const OUT = join(APP, 'src', 'ui', 'site');

mkdirSync(join(OUT, 'fonts'), { recursive: true });
copyFileSync(join(SITE, 'styles', 'tokens.css'), join(OUT, 'tokens.css'));
const fonts = readFileSync(join(SITE, 'styles', 'fonts.css'), 'utf8');
const files = [...fonts.matchAll(/url\('\.\.\/assets\/fonts\/([^']+)'\)/g)].map((m) => m[1]);
for (const f of new Set(files)) copyFileSync(join(SITE, 'assets', 'fonts', f), join(OUT, 'fonts', f));
writeFileSync(join(OUT, 'fonts.css'), fonts.replaceAll("url('../assets/fonts/", "url('fonts/"));
// the logo is the site's favicon; the title bar's icons are the site's own (Font Awesome Pro Duotone, drawn as
// the site draws them: src/site/design/icons.ts), the few the app uses
copyFileSync(resolve(APP, '..', '..', 'public', 'favicon.svg'), join(OUT, 'logo.svg'));
const { ICON_DATA } = await import(pathToFileURL(join(SITE, 'design', 'iconData.ts')).href);
const USED = ['external', 'chevron-down'];
const icons = Object.fromEntries(
  USED.map((name) => {
    const i = ICON_DATA[name];
    const secondary = i.secondary ? `<path class="icon-secondary" d="${i.secondary}"/>` : '';
    return [name, { viewBox: `0 0 ${i.width} 512`, body: `${secondary}<path class="icon-primary" d="${i.primary}"/>` }];
  }),
);
writeFileSync(join(OUT, 'icons.js'), `// Generated by scripts/sync-ui.mjs from the site's icon set. Never hand-edit.\nexport const ICONS = ${JSON.stringify(icons)};\n`);
console.log(`synced the site's tokens, ${new Set(files).size} fonts, its logo and ${USED.length} icons into src/ui/site/`);
